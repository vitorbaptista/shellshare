/// Get the current terminal size using ioctl (TIOCGWINSZ) via `term_size`.
/// Falls back to 80x24 when not attached to a terminal.
#[allow(clippy::cast_possible_truncation)] // Terminal dimensions always fit in u16
fn get_terminal_size() -> TermSize {
    term_size::dimensions()
        .map(|(cols, rows)| TermSize {
            cols: cols as u16,
            rows: rows as u16,
        })
        .unwrap_or_default()
}

/// What viewers should be told to render the broadcast in: either a
/// built-in theme by name, or this terminal's own colors by value.
///
/// Both are carried in the `size` control message and both end up in
/// the same `applyTheme` path in `public/javascript/room.js`; the difference
/// is only whether the viewer looks the theme up or is handed it.
pub enum ThemeChoice {
    Named(String),
    Detected(termtheme::TerminalColors),
}

/// Turn the validated `--theme` value into what goes on the wire.
///
/// `auto` (the default) asks the terminal; anything else is a name the
/// user chose and is passed through untouched - an explicit `--theme`
/// must never be second-guessed by detection. Detection failing is the
/// ordinary case on Windows, in CI, over a pipe with no controlling
/// terminal, and on any terminal that ignores OSC color queries, so it
/// lands on the same theme the CLI defaulted to before this existed.
fn resolve_theme(theme: Option<String>) -> ThemeChoice {
    match theme {
        Some(name) if name != crate::themes::AUTO => ThemeChoice::Named(name),
        _ => termtheme::detect().map_or_else(
            || ThemeChoice::Named(crate::themes::FALLBACK.to_string()),
            ThemeChoice::Detected,
        ),
    }
}

/// Client configuration arguments
pub struct ClientArgs {
    pub server: String,
    /// URL viewers should use when it differs from the broadcast URL
    /// (e.g. a tunnel in front of the local server); the share link is
    /// printed with this, while the transport still talks to `server`
    pub display_server: Option<String>,
    pub room: Option<String>,
    pub password: Option<String>,
    /// Print machine-readable JSON events to stdout instead of prose
    pub json: bool,
    /// Command to run instead of an interactive shell (`shellshare exec`);
    /// the broadcast ends when it exits and its exit code is propagated
    pub exec: Option<Vec<String>>,
    /// Viewer color theme, already validated against
    /// `themes::selectable_names()` - so this is a name from
    /// `themes.json` OR the literal `themes::AUTO`, which is not a
    /// theme and must be resolved (see `resolve_theme`) before any
    /// lookup by name
    pub theme: Option<String>,
    /// End-to-end encrypt the broadcast (the default). When false the
    /// terminal is sent in plaintext - for viewers on plain HTTP, where
    /// browsers can't decrypt
    pub encrypt: bool,
}

/// Environment variable carrying the live broadcast's share URL into the
/// spawned shell, so `shellshare status` can re-print it from inside the
/// session. Kept in memory only - never written to disk.
pub const ENV_URL: &str = "SHELLSHARE_URL";
/// Environment variable carrying the live broadcast's room name.
pub const ENV_ROOM: &str = "SHELLSHARE_ROOM";

/// The live session details exported into the spawned shell's environment.
pub struct SessionEnv<'a> {
    pub url: &'a str,
    pub room: &'a str,
}

/// Generate a random 18-character alphanumeric room ID
fn generate_room_id() -> String {
    const CHARSET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
    let mut rng = rand::thread_rng();

    // Exactly 18 chars: the viewer recognizes auto-generated ids by this
    // length to keep them out of the tab title (isAutoGeneratedRoom in
    // public/javascript/room.js), so the length must stay in lockstep.
    (0..18)
        .map(|_| {
            let idx = rng.gen_range(0..CHARSET.len());
            CHARSET[idx] as char
        })
        .collect()
}

/// Get the default password (MAC address as integer, like Python's `uuid.getnode()`)
fn get_default_password() -> String {
    if let Ok(Some(mac)) = mac_address::get_mac_address() {
        // Convert MAC address bytes to an integer (like Python's uuid.getnode())
        let bytes = mac.bytes();
        let mut value: u64 = 0;
        for &byte in &bytes {
            value = (value << 8) | u64::from(byte);
        }
        value.to_string()
    } else {
        // Fallback to a random value if MAC address is unavailable
        let mut rng = rand::thread_rng();
        rng.gen::<u64>().to_string()
    }
}

/// Whether browsers will treat the share link as a secure context.
/// `WebCrypto` (which the viewer needs to decrypt) only exists on https
/// pages, localhost, and loopback addresses.
///
/// Sibling loopback logic lives in `main.rs`'s `serve()`, but operates
/// on the raw `--host` arg (no scheme, plus wildcard detection), so the
/// two intentionally don't share a parser - keep their notions of
/// "loopback" consistent if either changes.
fn is_secure_context_url(base: &str) -> bool {
    let Some(rest) = base.strip_prefix("http://") else {
        return true; // https
    };
    let authority = rest.split('/').next().unwrap_or(rest);
    // Strip the port; IPv6 hosts are bracketed in URLs
    let host = authority.strip_prefix('[').map_or_else(
        || authority.rsplit_once(':').map_or(authority, |(h, _)| h),
        |h| h.split(']').next().unwrap_or(h),
    );
    let host = host.to_ascii_lowercase();
    host == "localhost"
        || host.ends_with(".localhost")
        || host
            .parse::<std::net::IpAddr>()
            .is_ok_and(|ip| ip.is_loopback())
}

/// Normalize server URL (ensure it has a scheme, strip trailing slashes)
fn normalize_server_url(server: &str) -> String {
    let server = if server.contains("://") {
        server.to_string()
    } else {
        format!("http://{server}")
    };
    server.trim_end_matches('/').to_string()
}

/// Emit one machine-readable event line on stdout (the `--json` contract:
/// whole JSON objects, one per line, flushed immediately so a pipe reader
/// sees the share URL before any terminal output follows).
fn emit_json(event: &serde_json::Value) {
    println!("{event}");
    let _ = io::stdout().flush();
}

/// Render a compact terminal QR code for the share URL. Failure should
/// never prevent a broadcast; the plain link remains the source of truth.
fn render_qr_code(url: &str) -> Option<String> {
    QrCode::new(url.as_bytes())
        .ok()
        .map(|code| code.render::<unicode::Dense1x2>().build())
}

/// Write the phone-scannable QR block for `url`, prefixed by an invitation
/// line. Best-effort: a QR render failure leaves the plain link as the
/// source of truth and prints nothing.
fn write_qr_code<W: Write>(writer: &mut W, url: &str) {
    if let Some(qr) = render_qr_code(url) {
        let _ = writeln!(writer);
        let _ = writeln!(writer, "Scan this QR code with your phone:");
        let _ = writeln!(writer, "{qr}");
    }
}

fn emit_human_sharing_message<W: Write>(writer: &mut W, share_url: &str, show_qr: bool) {
    let _ = writeln!(writer, "Sharing terminal in {share_url}");

    if show_qr {
        write_qr_code(writer, share_url);
    }

    let _ = writer.flush();
}

/// `shellshare status`: re-print the link (and QR) for the broadcast this
/// terminal is part of. The share URL is read from the `SHELLSHARE_URL`
/// environment variable that the broadcaster exports into the shell it
/// spawns, so this works only from inside a live shellshare session - and
/// without anything having been written to disk. Returns the exit code:
/// 0 when a session is found, 1 otherwise.
pub fn status(json: bool) -> i32 {
    let url = std::env::var(ENV_URL).ok().filter(|u| !u.is_empty());
    let Some(url) = url else {
        if json {
            // Mirror the --json contract: errors go to stderr, exit non-zero.
            eprintln!("ERROR: not inside a shellshare session");
        } else {
            eprintln!(
                "Not inside a shellshare session. Run `shellshare` first, then \
                 `shellshare status` from within the shared shell to see the link."
            );
        }
        return 1;
    };

    if json {
        let room = std::env::var(ENV_ROOM).ok();
        emit_json(&serde_json::json!({ "url": url, "room": room }));
        return 0;
    }

    let mut stdout = io::stdout();
    let _ = writeln!(stdout, "Sharing this terminal at {url}");
    if stdout.is_terminal() {
        write_qr_code(&mut stdout, &url);
    }
    let _ = stdout.flush();
    0
}

/// Run the shellshare client. Returns the exit code to propagate: the
/// child command's status for `exec`, otherwise 0.
pub fn run(args: ClientArgs) -> Result<i32, Box<dyn std::error::Error>> {
    let server = normalize_server_url(&args.server);
    let share_base = args
        .display_server
        .map_or_else(|| server.clone(), |s| normalize_server_url(&s));
    let room = args.room.unwrap_or_else(generate_room_id);
    let password = args.password.unwrap_or_else(get_default_password);

    // Build room path (r/{room})
    let room_path = format!("r/{room}");

    // Encrypted by default. The key goes only into the printed link's
    // #fragment - browsers never send fragments, so the server cannot
    // see it. Derived from this machine and the room name, so a named
    // room keeps one reusable link across restarts. --disable-encryption
    // drops to plaintext for viewers on plain HTTP (no WebCrypto there)
    let (cipher, share_url) = if args.encrypt {
        let (cipher, key) = crypto::Encryptor::for_room(&room);
        (Some(cipher), format!("{share_base}/{room_path}#{key}"))
    } else {
        (None, format!("{share_base}/{room_path}"))
    };
    if args.encrypt {
        if !is_secure_context_url(&share_base) {
            eprintln!(
                "WARNING: viewers can only decrypt on https or localhost; \
                 the link below is plain http, so browsers will refuse. \
                 For sharing over a plain-HTTP local network, run with \
                 --disable-encryption."
            );
        }
    } else {
        eprintln!(
            "WARNING: --disable-encryption is set; this broadcast is NOT \
             encrypted, so the server and anyone on the network can read \
             the terminal."
        );
    }

    // Connecting claims the room (or fails on a password mismatch), so
    // a broadcast that can never work is reported before the terminal
    // is handed over to the shell. Failures must propagate (not exit):
    // the caller may hold a tunnel whose cleanup an exit would skip
    let size = get_terminal_size();
    let theme = resolve_theme(args.theme);
    let transport = ws::Transport::connect(&server, &room_path, &password, size, theme, cipher)?;

    // A termination signal only flips flags; the loops below own the
    // transport and flush on their way out
    let running = Arc::new(AtomicBool::new(true));
    let forced = Arc::new(AtomicBool::new(false));
    install_signal_handlers(&running, &forced)?;

    if args.json {
        emit_json(&serde_json::json!({
            "event": "sharing",
            "url": share_url,
            "room": room,
            "server": server,
            "encrypted": args.encrypt,
        }));
    }

    // Pipe/redirect into bare shellshare -> relay stdin verbatim; a TTY
    // (a human) or `exec` (an explicit command) spawns a PTY instead.
    let stream_mode = args.exec.is_none() && !io::stdin().is_terminal();

    let exit_code = if stream_mode {
        // Stream mode - prose goes to stderr (stdout may be piped onward)
        if !args.json {
            let mut stderr = io::stderr();
            let show_qr = stderr.is_terminal();
            emit_human_sharing_message(&mut stderr, &share_url, show_qr);
        }

        // Read from stdin, tee to stdout, and stream to server. `--json`
        // owns stdout for the event protocol, so it opts out of the tee.
        stream_stdin(transport, &running, &forced, !args.json);

        if !args.json {
            eprintln!("End of transmission.");
        }
        0
    } else {
        // Script mode - prose goes to stdout. The interactive niceties
        // only make sense for a human on a TTY; scripts and agents get
        // the JSON contract (or nothing) instead.
        if !args.json {
            if io::stdout().is_terminal() && (size.rows > 30 || size.cols > 160) {
                println!("Current terminal size is {}x{}.", size.rows, size.cols);
                println!("It's too big to be viewed on smaller screens.");
                println!("You can resize it anytime.");
            }

            let mut stdout = io::stdout();
            let show_qr = stdout.is_terminal();
            emit_human_sharing_message(&mut stdout, &share_url, show_qr);
        }

        // Run script mode with PTY. The share URL and room ride into the
        // shell's environment so `shellshare status` can recover the link.
        let session = SessionEnv {
            url: &share_url,
            room: &room,
        };
        let code = script::run_script_mode(transport, &running, args.exec.as_deref(), &session)?;

        if !args.json {
            println!("End of transmission.");
        }
        code
    };

    if args.json {
        // PTY output is raw bytes and may leave stdout mid-line; start
        // the event on a fresh line so it stays parseable as a whole line
        if !stream_mode {
            println!();
        }
        emit_json(&serde_json::json!({
            "event": "end",
            "exit_code": exit_code,
        }));
    }

    Ok(exit_code)
}

/// Install the process-wide termination handlers.
///
/// Ctrl+C is the odd one out. The terminal delivers SIGINT to the whole
/// foreground process group, so in a pipe the producer is dying of the same
/// signal and its last bytes are still worth relaying - `stream_stdin` keeps
/// draining and only a second press cuts that short. The other two stop at
/// once, which is what all three did before the drain existed: SIGTERM
/// arrives alone (a supervisor, `kill`), so there is nobody to wait for,
/// and waiting would only lose the flush to the follow-up SIGKILL. SIGHUP
/// *is* group-delivered like SIGINT, but it means the terminal is gone - so
/// nobody is watching the link, and the second press that escapes a drain
/// could never be typed.
///
/// Note that a second SIGINT only arms the force-quit if it is a distinct
/// delivery: signals are not queued, so two arriving within the same
/// microseconds collapse into one. A keyboard is milliseconds apart, but a
/// programmatic sender should leave a gap.
#[cfg(unix)]
fn install_signal_handlers(
    running: &Arc<AtomicBool>,
    forced: &Arc<AtomicBool>,
) -> Result<(), Box<dyn std::error::Error>> {
    use signal_hook::consts::{SIGHUP, SIGINT, SIGTERM};
    use signal_hook::iterator::Signals;

    let mut signals = Signals::new([SIGINT, SIGTERM, SIGHUP])?;
    let running = running.clone();
    let forced = forced.clone();
    thread::spawn(move || {
        for signal in signals.forever() {
            let already_stopping = !running.swap(false, Ordering::SeqCst);
            if already_stopping || signal != SIGINT {
                forced.store(true, Ordering::SeqCst);
            }
        }
    });
    Ok(())
}

/// Windows delivers Ctrl+C to every process attached to the console, so it
/// gets the same drain-then-force treatment as SIGINT.
#[cfg(not(unix))]
fn install_signal_handlers(
    running: &Arc<AtomicBool>,
    forced: &Arc<AtomicBool>,
) -> Result<(), Box<dyn std::error::Error>> {
    let running = running.clone();
    let forced = forced.clone();
    ctrlc::set_handler(move || {
        if !running.swap(false, Ordering::SeqCst) {
            forced.store(true, Ordering::SeqCst);
        }
    })?;
    Ok(())
}

/// Translate lone LF into CRLF, writing the result into `out`.
///
/// A raw pipe delivers a log's Unix `\n` line endings, but the viewer is a
/// terminal emulator (xterm.js) where `\n` is a line feed - cursor down, same
/// column - and only `\r` returns to column 0. So bare LFs render as a
/// staircase. A shell session gets `\n` -> `\r\n` for free from the PTY's
/// ONLCR; stream mode has no PTY, so we replicate it here. `prev_was_cr`
/// carries the "last byte was CR" state across chunk boundaries so an existing
/// CRLF (or a CR split across two reads) is never doubled into CR-CR-LF.
fn lf_to_crlf(input: &[u8], prev_was_cr: &mut bool, out: &mut Vec<u8>) {
    out.clear();
    for &byte in input {
        if byte == b'\n' && !*prev_was_cr {
            out.push(b'\r');
        }
        out.push(byte);
        *prev_was_cr = byte == b'\r';
    }
}

/// Stream stdin to the server: relay bytes until EOF. When `echo_stdout` is
/// set, also tee each chunk to stdout (verbatim) so the local pipeline keeps
/// working - `journalctl --follow | shellshare` still shows and forwards its
/// output. `--json` clears the flag because that mode reserves stdout for the
/// event protocol. A broken downstream pipe (e.g. `| head`) must not abort the
/// broadcast, so stdout write errors are ignored - the broadcast is the job.
///
/// Only the broadcast is normalized to CRLF (see `lf_to_crlf`); the tee stays
/// verbatim so a downstream command sees exactly what was piped in and the
/// local terminal applies its own ONLCR.
///
/// stdin is read on its own thread so this loop can wake on a timer instead of
/// parking inside a blocking read. A quiet producer (`journalctl -f` on an idle
/// unit) emits nothing for long stretches, and the transport only pings - and
/// only retries buffered data - from `tick`. Without those pings the server
/// declares the broadcaster dead after 90s and flips every viewer's indicator
/// offline on a broadcast that is still perfectly live. It also keeps a drain
/// responsive: a second Ctrl+C lands within a tick instead of after the
/// producer's next line.
fn stream_stdin(
    mut transport: ws::Transport,
    running: &AtomicBool,
    forced: &AtomicBool,
    echo_stdout: bool,
) {
    /// How long to wait for input before letting the transport breathe.
    const IDLE_TICK: Duration = Duration::from_millis(50);
    /// How long a drain runs before it explains the wait. A producer that
    /// stops instantly stays silent; anything with children to reap (honcho
    /// takes ~1.5s, compose longer) will trip it, which is fine - that is
    /// exactly when a user starts wondering whether Ctrl+C did anything.
    const DRAIN_HINT_DELAY: Duration = Duration::from_secs(1);

    // Bounded, so a fast producer on a slow uplink still blocks in its own
    // write to our pipe rather than piling the whole stream into memory -
    // the backpressure the blocking read used to provide for free.
    let (tx, rx) = mpsc::sync_channel::<Vec<u8>>(64);
    thread::spawn(move || {
        let mut buffer = [0u8; 4096];
        let mut stdout = io::stdout();
        loop {
            let bytes_read = match io::stdin().read(&mut buffer) {
                Ok(0) => break, // EOF
                Ok(bytes_read) => bytes_read,
                // Defensive: signal-hook registers with SA_RESTART, so the
                // kernel resumes this read and an interrupted one never
                // surfaces here. If that ever changes, treating it as EOF
                // would end the stream on the very signal that starts the
                // drain, so say `continue` out loud
                Err(e) if e.kind() == io::ErrorKind::Interrupted => continue,
                // Any other read error ends the stream, same as EOF: the
                // sender sees the dropped channel and shuts down cleanly
                Err(_) => break,
            };
            let chunk = &buffer[..bytes_read];

            if echo_stdout {
                // Fire-and-forget: flush so `--follow` streams live; a dead
                // downstream just means the local echo stops, not the broadcast.
                let _ = stdout.write_all(chunk);
                let _ = stdout.flush();
            }

            // Deliberately no `running` check: Ctrl+C starts a drain, and
            // quitting here would discard the very bytes it waits for. A
            // forced exit drops the receiver, which ends this thread.
            if tx.send(chunk.to_vec()).is_err() {
                break;
            }
        }
    });

    let mut broadcast = Vec::new();
    let mut prev_was_cr = false;
    let mut signalled_at: Option<Instant> = None;
    let mut hinted = false;

    loop {
        // Only a forced exit leaves early - a second Ctrl+C, or a SIGTERM /
        // SIGHUP, which never wait. A first Ctrl+C reached the whole
        // pipeline, so the producer is on its way out and its last bytes are
        // still worth relaying; EOF is the normal exit.
        if forced.load(Ordering::SeqCst) {
            break;
        }

        // A drain with a silent producer is indistinguishable from a hang, so
        // say what is happening - once, and only if the wait lasts long
        // enough to be noticed.
        if !hinted && !running.load(Ordering::SeqCst) {
            let since = *signalled_at.get_or_insert_with(Instant::now);
            if since.elapsed() >= DRAIN_HINT_DELAY {
                hinted = true;
                // Leading CR like the ERROR lines below: stream mode has no
                // raw mode of its own, but it is routinely run inside a
                // session that does
                eprintln!("\rWaiting for input to finish. Press Ctrl+C again to quit now.");
            }
        }

        let size = get_terminal_size();
        let result = match rx.recv_timeout(IDLE_TICK) {
            Ok(chunk) => {
                lf_to_crlf(&chunk, &mut prev_was_cr, &mut broadcast);
                transport.send(&broadcast, size)
            }
            // Idle: keep the connection (and so the room) alive, and let
            // the transport retry anything still buffered
            Err(mpsc::RecvTimeoutError::Timeout) => transport.tick(size),
            // The reader hit EOF; everything it queued has been drained
            Err(mpsc::RecvTimeoutError::Disconnected) => break,
        };

        if let Err(e) = result {
            eprintln!("\r\nERROR: {e}");
            eprintln!("\rERROR: Exit shellshare and try again later.");
            // The room belongs to someone else now: draining our buffer
            // into it would be someone else's output, so skip the
            // shutdown flush entirely
            return;
        }
    }

    transport.shutdown();
}
