(function () {
  'use strict';

  // Theme definitions the page carries in a JSON block: the
  // server injects them there so this file stays a static,
  // immutably cached asset shared by every room.
  var THEMES = JSON.parse(
    document.getElementById('themes').textContent);
  // The CLI's default --theme, used until a size message names one.
  // Must stay in lockstep with the default in src/main.rs and with the
  // fallback colors hard-coded in room.css.
  var DEFAULT_THEME = 'tango';
  // Matches the base terminal font size in room.css
  var BASE_FONT_PX = 14;
  // A raw WebSocket to /ws/v + this page's path: binary frames are
  // terminal bytes, JSON text frames are control events (size,
  // usersCount, broadcasting) - the mirror of the broadcaster's
  // ingest protocol. The room is the URL, so there is no join
  // handshake to confirm or lose; the server replays the room
  // snapshot on every (re)connect.
  var room = window.location.pathname;
  var WS_URL =
    (window.location.protocol === 'https:' ? 'wss://' : 'ws://') +
    window.location.host + '/ws/v' + room;
  // A user-chosen room name goes in the tab title, but an
  // auto-generated id is noise. We can't see the broadcaster's CLI,
  // so we guess from the name's length: generate_room_id (src/cli/
  // mod.rs) emits exactly 18 chars, and a human "standup" or
  // "team-demo" almost never lands on exactly that length. Mistitling
  // a rare 18-char custom name is harmless, so this cheap heuristic
  // is enough. Must stay in lockstep with generate_room_id's length.
  var GENERATED_ROOM_ID_LENGTH = 18;
  function isAutoGeneratedRoom(name) {
    return name.length === GENERATED_ROOM_ID_LENGTH;
  }
  (function setTitleFromRoom() {
    var match = /\/r\/([^/]+)\/?$/.exec(window.location.pathname);
    if (!match) {
      return;
    }
    var name;
    try {
      name = decodeURIComponent(match[1]);
    } catch (e) {
      name = match[1];
    }
    if (!isAutoGeneratedRoom(name)) {
      document.title = name + ' - shellshare';
    }
  })();
  // Broadcasts are end-to-end encrypted by default: the key rides
  // in the URL fragment, which browsers never send to the server,
  // and each message is a sequence of whole records -
  // [u32 BE: N][12-byte nonce][ciphertext+16-byte tag], AES-256-GCM
  // - that only this page can open; the server relays opaque bytes.
  // A broadcaster on --disable-encryption sends plaintext instead
  // (no fragment); the size message's `encrypted` flag tells the
  // two apart. Must stay in lockstep with src/cli/crypto.rs.
  var keyHex = window.location.hash.replace(/^#/, '');
  // Set once the size message reveals the room is encrypted but we
  // have no key (the link's fragment was stripped); until then a
  // keyless page can't tell an encrypted room from a plaintext one
  var encryptedWithoutKey = false;
  var term = null;
  var currentSize = {cols: 80, rows: 30};
  // Output that arrives before the terminal exists (creation waits
  // for the webfont) is queued and flushed on creation
  var pendingWrites = [];
  var joinedBefore = false;
  var onlineCounter = document.getElementById('online-counter');
  var onlineCounterPlural = document.getElementById('online-counter-plural');
  var broadcastStatus = document.getElementById('broadcast-status');
  var broadcastStatusText =
    document.getElementById('broadcast-status-text');
  var terminalContainer = document.getElementById('terminal');
  var fullscreenToggle = document.getElementById('fullscreen-toggle');
  var immersiveOverlay = document.getElementById('immersive-overlay');
  var favicon = document.getElementById('favicon');
  var cryptoNotice = document.getElementById('crypto-notice');

  function showCryptoNotice(text) {
    cryptoNotice.textContent = text;
    cryptoNotice.hidden = false;
    terminalContainer.classList.add('crypto-blocked');
  }

  function hideCryptoNotice() {
    cryptoNotice.hidden = true;
    terminalContainer.classList.remove('crypto-blocked');
  }

  function hexToBytes(hexString) {
    if (hexString.length % 2 || !/^[0-9a-fA-F]*$/.test(hexString)) {
      return null;
    }
    var out = new Uint8Array(hexString.length / 2);
    for (var i = 0; i < out.length; i++) {
      out[i] = parseInt(hexString.substr(i * 2, 2), 16);
    }
    return out;
  }

  // Resolves to the AES-GCM key when the link carries a usable one.
  // A missing fragment is NOT flagged here - it might be a plaintext
  // (--disable-encryption) room - so the verdict waits for the size
  // message's `encrypted` flag (see onSize). A present-but-broken
  // fragment is flagged now: the notice explains why nothing renders.
  var cryptoKeyPromise = null;
  if (keyHex) {
    if (!(window.crypto && window.crypto.subtle)) {
      // WebCrypto only exists in secure contexts
      showCryptoNotice('Encrypted broadcast. Open this link over ' +
        'https or from localhost to view it.');
    } else {
      var keyBytes = hexToBytes(keyHex);
      if (!keyBytes || keyBytes.length !== 32) {
        showCryptoNotice('Invalid decryption key. Ask the ' +
          'broadcaster for the full share link.');
      } else {
        cryptoKeyPromise = window.crypto.subtle.importKey(
          'raw', keyBytes, {name: 'AES-GCM'}, false, ['decrypt']);
      }
    }
  }

  // Each message is a run of whole records (the server stores and
  // concatenates whole frames). Resolves to {chunks, decryptable}:
  // every record this key opens, in order, plus whether any did.
  //
  // A record that fails to decrypt is SKIPPED, not fatal - history
  // can mix keys when a room is re-broadcast (old-key records sit
  // in front of the new-key ones), and the records this key opens
  // may be a suffix, not a prefix. Only a structurally broken
  // length frame (not our wire format at all - e.g. a plaintext
  // room opened with a key) rejects, since we can't resync past it.
  function decryptRecords(key, bytes) {
    var chunks = [];
    var decryptable = false;
    var offset = 0;
    function step() {
      if (offset >= bytes.length) {
        return Promise.resolve(
          {chunks: chunks, decryptable: decryptable});
      }
      if (bytes.length - offset < 4) {
        return Promise.reject(new Error('malformed framing'));
      }
      var view = new DataView(
        bytes.buffer, bytes.byteOffset + offset, 4);
      var recordLen = view.getUint32(0);
      // Minimum: 12-byte nonce + 16-byte tag
      if (recordLen < 28 || bytes.length - offset - 4 < recordLen) {
        return Promise.reject(new Error('malformed framing'));
      }
      var body = offset + 4;
      var iv = bytes.subarray(body, body + 12);
      var ciphertext = bytes.subarray(body + 12, body + recordLen);
      offset = body + recordLen;
      return window.crypto.subtle.decrypt(
        {name: 'AES-GCM', iv: iv}, key, ciphertext
      ).then(function (plain) {
        decryptable = true;
        chunks.push(new Uint8Array(plain));
        return step();
      }, function () {
        // Wrong key for this record; the framing is intact, so
        // advance and keep trying the rest
        return step();
      });
    }
    return step();
  }

  function showWrongKeyNotice() {
    showCryptoNotice('Wrong decryption key. Ask the broadcaster ' +
      'for the current share link.');
  }

  // Decryption is asynchronous, so writes go through one promise
  // chain to stay in receive order. The epoch discards in-flight
  // decryptions across a rejoin: the server replays history then,
  // and pre-disconnect output resolving late would garble it.
  var decryptEpoch = 0;
  var decryptChain = Promise.resolve();
  function enqueueEncrypted(bytes) {
    var epoch = decryptEpoch;
    decryptChain = decryptChain.then(function () {
      return cryptoKeyPromise.then(function (key) {
        return decryptRecords(key, bytes);
      }).then(function (result) {
        if (epoch !== decryptEpoch) {
          return;
        }
        for (var i = 0; i < result.chunks.length; i++) {
          writeBytes(result.chunks[i]);
        }
        // Records that opened prove the key is right (some history
        // records may predate a re-broadcast and stay sealed under
        // the old key - that's expected, not an error). Flag the
        // stream only when nothing in this message decrypted.
        if (result.chunks.length > 0) {
          hideCryptoNotice();
        } else if (bytes.length > 0) {
          showWrongKeyNotice();
        }
      }, function () {
        // Not our record framing at all (wrong/plaintext stream)
        if (epoch === decryptEpoch) {
          showWrongKeyNotice();
        }
      });
    });
  }

  function writeBytes(bytes) {
    if (term) {
      term.write(bytes);
    } else {
      pendingWrites.push(bytes);
    }
  }

  // While the room is live the favicon's underscore cursor blinks:
  // alternate between the regular icon and one with the cursor
  // erased. Animated GIF favicons don't animate in Chrome/Safari,
  // so the swap is driven from here.
  var FAVICON_CURSOR_ON = '/favicon.png';
  var FAVICON_CURSOR_OFF = '/favicon-cursor-off.png';
  var faviconTimer = null;
  var faviconCursorOn = true;
  // Pre-fetch so the first swaps don't flicker through a blank icon
  new Image().src = FAVICON_CURSOR_OFF;

  function setFaviconBlink(blinking) {
    if (blinking && !faviconTimer) {
      faviconTimer = setInterval(function () {
        faviconCursorOn = !faviconCursorOn;
        favicon.href = faviconCursorOn ?
          FAVICON_CURSOR_ON : FAVICON_CURSOR_OFF;
      }, 600);
    } else if (!blinking && faviconTimer) {
      clearInterval(faviconTimer);
      faviconTimer = null;
      faviconCursorOn = true;
      favicon.href = FAVICON_CURSOR_ON;
    }
  }

  // xterm.js measures the font once at open(): wait for the
  // webfont so cell metrics come from Inconsolata, not a fallback.
  // load() also resolves when the font is unavailable, so this can
  // only delay creation, never block it.
  var fontReady = document.fonts && document.fonts.load ?
    document.fonts.load(BASE_FONT_PX + "px 'Inconsolata'") :
    Promise.resolve();
  fontReady.catch(function () {}).then(createTerminal);

  function createTerminal() {
    term = new Terminal({
      cols: currentSize.cols,
      rows: currentSize.rows,
      fontFamily: "'Inconsolata', 'Symbols Nerd Font', monospace",
      fontSize: BASE_FONT_PX,
      scrollback: 5000,
      // Read-only viewer: keystrokes must not reach the terminal
      disableStdin: true,
      // The Unicode 11 addon needs the proposed API surface
      allowProposedApi: true,
    });
    // Wide-character widths per Unicode 11 instead of xterm's
    // Unicode 6 default (emoji and CJK render at correct width).
    // A failed addon script must cost only character widths, not
    // the whole viewer.
    if (typeof Unicode11Addon !== 'undefined') {
      term.loadAddon(new Unicode11Addon.Unicode11Addon());
      term.unicode.activeVersion = '11';
    }
    applyTheme(currentSize.theme);
    term.open(terminalContainer);
    // Read-only viewer: xterm focuses its hidden textarea on
    // click, which then swallows keydown events before they reach
    // the page (breaking the `f` fullscreen toggle and Ctrl+C
    // copy below). Nothing needs that focus - there is no input -
    // so refuse it. Mouse selection is unaffected.
    term.textarea.tabIndex = -1;
    term.textarea.addEventListener('focus', function () {
      term.textarea.blur();
    });
    enableWebglRenderer();
    for (var i = 0; i < pendingWrites.length; i++) {
      term.write(pendingWrites[i]);
    }
    pendingWrites = [];
    // The renderer caches glyphs in a texture atlas, so fonts
    // that load lazily after first paint (the Nerd Font symbols
    // fallback, non-latin Inconsolata subsets) would otherwise
    // stay rendered as the fallback glyphs they were drawn with.
    // Clearing the atlas empties the glyph cache, but the WebGL
    // renderer only re-rasterizes cells it considers dirty - cells
    // on a settled screen (a static TUI pane) keep pointing at the
    // now-empty atlas and, at fractional devicePixelRatio, paint as
    // solid black boxes until something rewrites them. Forcing a
    // full repaint re-rasterizes every visible cell so none go dark.
    if (document.fonts && document.fonts.addEventListener) {
      document.fonts.addEventListener('loadingdone', function () {
        term.clearTextureAtlas();
        term.refresh(0, term.rows - 1);
      });
    }
    // For the e2e suite and console debugging: the WebGL renderer
    // leaves no text in the DOM to scrape
    window.term = term;
    fitTerminal();
  }

  // GPU renderer with graceful degradation: a load failure (no
  // WebGL2) or a later context loss falls back to xterm's DOM
  // renderer, which needs no addon
  function enableWebglRenderer() {
    if (typeof WebglAddon === 'undefined') {
      return;
    }
    try {
      // Static terminal panes must survive browser compositor idle
      // clears; otherwise only cells that keep changing repaint.
      var webgl = new WebglAddon.WebglAddon(true);
      webgl.onContextLoss(function () {
        webgl.dispose();
      });
      term.loadAddon(webgl);
    } catch (e) {
      // DOM renderer remains active
    }
  }

  // The rendered buffer (scrollback + screen) as plain text; used
  // by the e2e suite, handy in the console
  window.shellshareText = function () {
    if (!term) {
      return '';
    }
    var buffer = term.buffer.active;
    var lines = [];
    for (var i = 0; i < buffer.length; i++) {
      var line = buffer.getLine(i);
      lines.push(line ? line.translateToString(true) : '');
    }
    return lines.join('\n');
  };

  // Reconnect with backoff on every close: the server replays the
  // room snapshot (size, history, broadcasting, usersCount) on
  // each connect, so a rejoin is a clean resync. The server also
  // disconnects viewers that fall hopelessly behind, on purpose -
  // this same path then recovers them.
  var RECONNECT_MIN_MS = 500;
  var RECONNECT_MAX_MS = 10000;
  var reconnectDelayMs = RECONNECT_MIN_MS;

  // Wipe the screen and everything still in flight toward it. Used
  // when the bytes that follow replace what came before rather than
  // continuing it: a reconnect (the server replays the history) and
  // a `reset` control event (the broadcaster started a new session
  // on a room that still held the previous one).
  //
  // RIS through the write queue, not term.reset(): writes are
  // asynchronous, so an out-of-band reset could run before leftover
  // chunks parse; queued RIS is ordered after them and also resets
  // the VT parser and UTF-8 decoder state they may have left
  // mid-sequence.
  //
  // Encrypted rooms additionally discard in-flight decryptions:
  // their plaintext would otherwise resolve after this reset and
  // replay superseded output on top of the fresh screen. A fresh
  // chain also keeps it from deepening across rejoins.
  function clearScreen() {
    decryptEpoch++;
    decryptChain = Promise.resolve();
    pendingWrites = [];
    if (term) {
      term.write('\x1bc');
    }
  }

  function connect() {
    var ws = new WebSocket(WS_URL);
    ws.binaryType = 'arraybuffer';
    ws.onopen = function () {
      if (joinedBefore) {
        // The server replays the room history on connect; start
        // from a clean screen instead of appending a duplicate.
        // The size is kept: the server re-sends it (before the
        // history) whenever the room has one.
        clearScreen();
      }
      joinedBefore = true;
    };
    ws.onmessage = function (event) {
      if (typeof event.data === 'string') {
        var control;
        try {
          control = JSON.parse(event.data);
        } catch (e) {
          return;
        }
        if (control.size) {
          onSize(control.size);
        }
        if (typeof control.usersCount === 'number') {
          // The snapshot terminator: only a connection that got
          // this far resets the reconnect backoff - a server that
          // accepts and immediately closes (overload) keeps
          // backing off instead of hammering every 500ms
          reconnectDelayMs = RECONNECT_MIN_MS;
          onUsersCount(control.usersCount);
        }
        if (typeof control.broadcasting === 'boolean') {
          onBroadcasting(control.broadcasting);
        }
        // A new session replaced whatever this room held
        if (control.reset === true) {
          clearScreen();
        }
        return;
      }
      onMessage(new Uint8Array(event.data));
    };
    // Our own connection is down: we can't know the broadcaster's
    // state, so report the session as offline until we resync
    ws.onclose = function () {
      setBroadcastStatus('offline');
      setFaviconBlink(false);
      // Jittered: a server restart disconnects every open tab at
      // once, and without jitter they all reconnect in synchronized
      // waves, each wave replaying the full history snapshot
      setTimeout(connect, reconnectDelayMs * (0.5 + Math.random()));
      reconnectDelayMs =
        Math.min(reconnectDelayMs * 2, RECONNECT_MAX_MS);
    };
  }
  connect();

  // textContent, not innerHTML: the count is always a number (the caller
  // checks) so nothing here can render markup either way, but a text sink
  // stays safe if that guard ever loosens - and it is what the assignment
  // means.
  function onUsersCount(onlineUsers) {
    onlineCounter.textContent = String(onlineUsers);
    onlineCounterPlural.textContent = onlineUsers == 1 ? '' : 's';
  }
  // Whether the broadcaster's client is attached to the room right
  // now (it pings even when idle, so "live" means the session is
  // open, not that output is flowing). The server reports the
  // current state on connect and every transition afterwards.
  function onBroadcasting(live) {
    setBroadcastStatus(live ? 'online' : 'offline');
    setFaviconBlink(live);
  }

  function setBroadcastStatus(state) {
    broadcastStatus.title = state;
    broadcastStatus.className = 'broadcast-status ' + state;
    // A real (visually hidden) text node, not an aria-label:
    // role="status" live regions only announce content changes
    broadcastStatusText.textContent = 'broadcaster ' + state;
  }
  function onMessage(bytes) {
    if (!bytes.length) {
      return;
    }
    if (keyHex) {
      // Decrypt mode. A broken key dropped cryptoKeyPromise to
      // null and the notice already explains why; drop the bytes
      if (cryptoKeyPromise) {
        enqueueEncrypted(bytes);
      }
      return;
    }
    if (encryptedWithoutKey) {
      // Encrypted room, no key in this link: never render ciphertext
      return;
    }
    // Plaintext (--disable-encryption) room: raw terminal bytes,
    // xterm.js does its own streaming UTF-8 decode
    writeBytes(bytes);
  }

  // The broadcaster controls the size: sanitize it so resize()
  // never throws (it requires positive integers) and a hostile
  // value can't make every viewer allocate a million-row buffer
  var MAX_DIMENSION = 1000;

  function clampDimension(value) {
    var n = Math.floor(value);
    return n >= 1 ? Math.min(n, MAX_DIMENSION) : 0;
  }

  function onSize(size) {
    if (!size) {
      return;
    }
    // The broadcaster marks encrypted streams in the size message
    // (it rides verbatim, like the theme), and size always precedes
    // content. A keyless page seeing this knows its link lost the
    // key, rather than mistaking ciphertext for a plaintext room.
    if (size.encrypted && !keyHex && !encryptedWithoutKey) {
      encryptedWithoutKey = true;
      showCryptoNotice('Missing decryption key. Ask the ' +
        'broadcaster for the full share link.');
    }
    var cols = clampDimension(size.cols);
    var rows = clampDimension(size.rows);
    if (!cols || !rows) {
      return;
    }
    var themeChanged = currentSize.theme !== size.theme;
    currentSize = {cols: cols, rows: rows, theme: size.theme};
    if (!term) {
      // Applied when the terminal is created
      return;
    }
    term.resize(cols, rows);
    if (themeChanged) {
      applyTheme(size.theme);
    }
    fitTerminal();
  }

  // Map a themes.json entry (16 ANSI palette colors plus
  // background and foreground) onto xterm's named theme slots.
  // Unknown or absent themes get the default look the page CSS
  // assumes (black background, light foreground).
  var ANSI_SLOTS = [
    'black', 'red', 'green', 'yellow',
    'blue', 'magenta', 'cyan', 'white',
    'brightBlack', 'brightRed', 'brightGreen', 'brightYellow',
    'brightBlue', 'brightMagenta', 'brightCyan', 'brightWhite',
  ];

  function applyTheme(name) {
    // Before the first size message (and for a theme this viewer
    // doesn't know) fall back to the CLI's default theme rather than
    // plain black/white: the terminal is created and painted as soon
    // as the font loads, so an arbitrary fallback flashes against the
    // theme that then lands - and tango is what most broadcasts send.
    // Same reasoning as the CSS fallbacks in room.css.
    var entry = THEMES[name] || THEMES[DEFAULT_THEME];
    var colors = {
      background: entry ? entry.background : '#000000',
      foreground: entry ? entry.foreground : '#f0f0f0',
    };
    if (entry && entry.palette && entry.palette.length >= 16) {
      for (var i = 0; i < ANSI_SLOTS.length; i++) {
        colors[ANSI_SLOTS[i]] = entry.palette[i];
      }
    }
    term.options.theme = colors;
    // The container peeks out around the canvas (padding, short
    // pages); keep it matched to the terminal background
    terminalContainer.style.backgroundColor = colors.background;
    applyPageChrome(colors, entry);
  }

  // Drive the page chrome (body/header/footer/links) from the
  // terminal theme so a dark terminal never blinds the viewer on a
  // white page, and a light theme gets a light page. The values ride
  // as CSS custom properties on <html> (see room.css); deciding
  // dark-vs-light from the background's luminance only picks the link
  // accent (a palette blue) and keeps text legible against it.
  function parseHex(hex) {
    if (typeof hex !== 'string' || !/^#[0-9a-fA-F]{6}$/.test(hex)) {
      return null;
    }
    return [
      parseInt(hex.substr(1, 2), 16),
      parseInt(hex.substr(3, 2), 16),
      parseInt(hex.substr(5, 2), 16),
    ];
  }

  function toHex(rgb) {
    return '#' + rgb.map(function (c) {
      var h = Math.round(Math.max(0, Math.min(255, c))).toString(16);
      return h.length === 1 ? '0' + h : h;
    }).join('');
  }

  // Perceived brightness (0-1) of an sRGB color
  function luminance(rgb) {
    return (0.2126 * rgb[0] + 0.7152 * rgb[1] + 0.0722 * rgb[2]) / 255;
  }

  // Blend two colors; t=0 returns a, t=1 returns b
  function mix(a, b, t) {
    return [
      a[0] + (b[0] - a[0]) * t,
      a[1] + (b[1] - a[1]) * t,
      a[2] + (b[2] - a[2]) * t,
    ];
  }

  function applyPageChrome(colors, entry) {
    // Only if even the default theme is missing from the injected
    // block: leave the page at the CSS defaults rather than forcing it
    // black. Normally entry is the broadcast theme, or tango until one
    // lands - and tango is exactly what those CSS defaults encode, so
    // applying it here is a no-op repaint, not a flash.
    if (!entry) {
      return;
    }
    var bg = parseHex(colors.background) || [18, 19, 20];
    var fg = parseHex(colors.foreground) || [204, 204, 204];
    var lum = luminance(bg);
    var dark = lum < 0.5;
    // Offset the page background from the terminal so the terminal
    // reads as a distinct surface instead of bleeding into the page.
    // Normally the page goes a bit darker (the terminal "floats"
    // above it); a near-black terminal can't go darker, so lift the
    // page instead. toHex clamps, so the shift never wraps.
    var SHIFT = 16;
    var dir = lum < 0.12 ? 1 : -1;
    var pageBg = toHex([
      bg[0] + dir * SHIFT, bg[1] + dir * SHIFT, bg[2] + dir * SHIFT,
    ]);
    // Muted text (footer, link hover): foreground faded toward the
    // background, staying readable on either tone
    var muted = toHex(mix(fg, bg, 0.45));
    // Link accent: the theme's own blue (bright blue on dark themes
    // for contrast, plain blue on light), falling back to foreground
    var palette = entry.palette;
    var accent = (palette && palette[dark ? 12 : 4]) || colors.foreground;
    var root = document.documentElement.style;
    root.setProperty('--page-bg', pageBg);
    root.setProperty('--page-fg', colors.foreground);
    root.setProperty('--page-muted', muted);
    root.setProperty('--page-accent', accent);
    // The first apply lands instantly (no fade from the pre-size
    // default); enable the smooth transition only afterwards, so a
    // live re-theme animates. Next frame, so this apply isn't caught.
    if (!pageChromeApplied) {
      pageChromeApplied = true;
      requestAnimationFrame(function () {
        document.body.classList.add('theme-transitions');
      });
    }
  }
  var pageChromeApplied = false;

  // Fullscreen: the `fullscreen` class on #terminal drives all
  // layout, so browsers without requestFullscreen on divs (iOS
  // Safari) still get a fill-the-page mode. The native API only
  // adds the OS chrome on top.
  function isFullscreen() {
    return terminalContainer.classList.contains('fullscreen');
  }

  function nativeFullscreenElement() {
    return document.fullscreenElement ||
           document.webkitFullscreenElement || null;
  }

  // Lock to landscape on entering immersive mode. Supported on
  // Android Chrome (only while fullscreen); a no-op everywhere it
  // isn't (notably iOS Safari, which has no orientation lock and no
  // element Fullscreen API - the fill-the-page class fallback plus
  // the CSS rotate nudge cover it there). Any rejection is silent.
  function lockLandscape() {
    try {
      var o = window.screen && window.screen.orientation;
      if (o && o.lock) {
        var p = o.lock('landscape');
        if (p && p.catch) {
          p.catch(function () {});
        }
      }
    } catch (e) {}
  }

  function unlockOrientation() {
    try {
      var o = window.screen && window.screen.orientation;
      if (o && o.unlock) {
        o.unlock();
      }
    } catch (e) {}
  }

  // Keep the screen awake while watching a live broadcast. The lock
  // is auto-released when the tab is hidden, so it is re-acquired on
  // visibilitychange while still immersive. Absent API or rejection
  // is a silent no-op.
  var wakeLock = null;
  // A request is asynchronous, and the native-fullscreen path calls
  // acquire twice in quick succession (enterFullscreen, then the
  // fullscreenchange handler) before the first resolves. Without a
  // pending guard both fire request('screen') and the second sentinel
  // orphans the first, which then leaks. The flag collapses concurrent
  // requests to one.
  var wakeLockPending = false;
  function acquireWakeLock() {
    if (wakeLock || wakeLockPending || !navigator.wakeLock) {
      return;
    }
    wakeLockPending = true;
    navigator.wakeLock.request('screen').then(function (lock) {
      wakeLockPending = false;
      // If we left immersive mode while the request was in flight,
      // drop this lock instead of holding one releaseWakeLock has
      // already missed.
      if (!isFullscreen()) {
        lock.release().catch(function () {});
        return;
      }
      wakeLock = lock;
      lock.addEventListener('release', function () {
        wakeLock = null;
      });
    }).catch(function () {
      wakeLockPending = false;
    });
  }

  function releaseWakeLock() {
    if (wakeLock) {
      wakeLock.release().catch(function () {});
      wakeLock = null;
    }
  }

  // Idempotent: both the class fallback (enterFullscreen, no native
  // event on iOS) and the native fullscreenchange handler call these,
  // and a re-entrant call must not double-lock or leak a wake lock.
  function enterImmersive() {
    lockLandscape();
    acquireWakeLock();
  }

  function exitImmersive() {
    unlockOrientation();
    releaseWakeLock();
  }

  function enterFullscreen() {
    terminalContainer.classList.add('fullscreen');
    var rfs = terminalContainer.requestFullscreen ||
              terminalContainer.webkitRequestFullscreen;
    if (rfs) {
      // Older webkit doesn't return a promise
      var result = rfs.call(terminalContainer);
      if (result && result.catch) {
        result.catch(function () {});
      }
    }
    // Runs inside the tap/keypress gesture, which orientation lock
    // requires. Native fullscreen also re-runs it from
    // onFullscreenChange; the class fallback (iOS) has no such event,
    // so this call is what covers it there.
    enterImmersive();
    fitTerminal();
  }

  function exitFullscreen() {
    if (nativeFullscreenElement()) {
      var result = (document.exitFullscreen ||
                    document.webkitExitFullscreen).call(document);
      if (result && result.catch) {
        result.catch(function () {});
      }
    }
    terminalContainer.classList.remove('fullscreen');
    exitImmersive();
    fitTerminal();
  }

  function toggleFullscreen() {
    if (isFullscreen()) {
      exitFullscreen();
    } else {
      enterFullscreen();
    }
  }

  // Scale the font so the broadcaster's cols×rows fill the screen.
  // xterm sizes its grid from options.fontSize: the rendered grid
  // (.xterm-screen) is measured, the font scaled proportionally,
  // then nudged down for rounding overflow. xterm re-renders after
  // a font-size change, so the nudge converges across animation
  // frames instead of measuring synchronously.
  var MIN_FONT_PX = 7;
  var fitScheduled = false;
  // Each fit invalidates any in-flight convergence loop
  var fitToken = 0;

  function setFontSize(px) {
    if (term.options.fontSize !== px) {
      term.options.fontSize = px;
    }
  }

  function screenRect() {
    var screen = term.element.querySelector('.xterm-screen');
    return screen ? screen.getBoundingClientRect() : null;
  }

  function overflowsWidth(rect) {
    return rect.width > terminalContainer.clientWidth;
  }

  function overflows(rect) {
    return overflowsWidth(rect) ||
           rect.height > terminalContainer.clientHeight;
  }

  // Touch devices (phones, tablets). Mouse/keyboard devices - even
  // ones with a touchscreen - keep a fine pointer and the desktop
  // behavior. Drives both the fit-to-width preview here and, in
  // room.css, the immersive overlay and rotate nudge.
  function isCoarsePointer() {
    return !!(window.matchMedia &&
              window.matchMedia('(pointer: coarse)').matches);
  }

  // Phone held in landscape. The not-fullscreen preview fits the
  // whole grid on screen here (see fitTerminal), and the immersive
  // overlay drops its "rotate to landscape" hint (room.css) - there's
  // nothing left to rotate.
  function isLandscape() {
    return !!(window.matchMedia &&
              window.matchMedia('(orientation: landscape)').matches);
  }

  // Height available to a viewport-pinned preview: everything below
  // the terminal's top edge. offsetTop is a layout offset (scroll
  // independent), so this stays stable as the live tail scrolls.
  function previewHeight() {
    return Math.max(0, window.innerHeight - terminalContainer.offsetTop);
  }

  // Three scaling regimes share one convergence loop:
  // - Fullscreen: fit the grid to both axes (fill the screen).
  // - Touch + portrait, not fullscreen: fit to WIDTH only, so every
  //   column shows without horizontal scroll. Height is free to grow
  //   and scroll - a small but complete "preview" the viewer taps to
  //   enter the readable landscape view.
  // - Touch + landscape, not fullscreen: the grid already has a wide
  //   aspect to fill, so fit BOTH axes into a viewport-bounded box.
  //   The whole session shows at once with no scroll, and the
  //   immersive overlay (inset:0 of that box) covers exactly the
  //   visible area instead of floating in an over-tall scroll height.
  // A fine-pointer page out of fullscreen keeps the base font
  // (desktop is unchanged).
  function fitTerminal() {
    if (!term || !term.element) {
      return;
    }
    var token = ++fitToken;
    var fs = isFullscreen();
    var preview = !fs && isCoarsePointer();
    // Pin the landscape preview to the viewport so both axes have a
    // bounded box to fit into; every other regime lets height follow
    // content (fullscreen fills the CSS-fixed box). border-box so the
    // height includes #terminal's padding - otherwise the padding
    // pushes the box (and the overlay covering it) past the viewport.
    if (preview && isLandscape()) {
      terminalContainer.style.boxSizing = 'border-box';
      terminalContainer.style.height = previewHeight() + 'px';
    } else {
      terminalContainer.style.boxSizing = '';
      terminalContainer.style.height = '';
    }
    if (!fs && !preview) {
      setFontSize(BASE_FONT_PX);
      return;
    }
    // Fullscreen and the landscape preview fit both axes; portrait
    // fits width only.
    var fitBoth = fs || isLandscape();
    // Cell dimensions are near-linear in font size, so the ratio
    // at the current size gives the target directly
    var rect = screenRect();
    if (!rect || !rect.width || !rect.height) {
      return;
    }
    var scaleW = terminalContainer.clientWidth / rect.width;
    var scale = fitBoth ?
      Math.min(scaleW, terminalContainer.clientHeight / rect.height) :
      scaleW;
    // Integer px keeps glyphs crisp
    setFontSize(Math.max(MIN_FONT_PX,
                         Math.floor(term.options.fontSize * scale)));
    requestAnimationFrame(function nudge() {
      var stillFs = isFullscreen();
      var stillPreview = !stillFs && isCoarsePointer();
      if (token !== fitToken || (!stillFs && !stillPreview)) {
        return;
      }
      var stillBoth = stillFs || isLandscape();
      var rect = screenRect();
      var over = stillBoth ? overflows(rect) : overflowsWidth(rect);
      if (rect && over && term.options.fontSize > MIN_FONT_PX) {
        setFontSize(term.options.fontSize - 1);
        requestAnimationFrame(nudge);
      }
    });
  }

  function scheduleFit() {
    if (fitScheduled) {
      return;
    }
    fitScheduled = true;
    requestAnimationFrame(function () {
      fitScheduled = false;
      fitTerminal();
    });
  }

  // The native state is authoritative whenever it changes: this
  // covers Esc and browser-UI exits, and re-syncs the class if a
  // pending requestFullscreen resolves after a rapid toggle. The
  // fallback path never fires this event, so its class handling
  // is untouched.
  function onFullscreenChange() {
    var entering = !!nativeFullscreenElement();
    terminalContainer.classList.toggle('fullscreen', entering);
    if (entering) {
      enterImmersive();
    } else {
      exitImmersive();
    }
    scheduleFit();
  }

  fullscreenToggle.addEventListener('click', toggleFullscreen);
  // On touch the overlay - not the corner toggle - is the entry
  // point (room.css hides the toggle and shows the overlay there).
  // It only ever shows out of fullscreen, so enter, don't toggle.
  immersiveOverlay.addEventListener('click', enterFullscreen);
  window.addEventListener('resize', scheduleFit);
  // The wake lock is dropped when the tab is hidden; take it back on
  // return if still watching immersively.
  document.addEventListener('visibilitychange', function () {
    if (document.visibilityState === 'visible' && isFullscreen()) {
      acquireWakeLock();
    }
  });
  document.addEventListener('fullscreenchange', onFullscreenChange);
  document.addEventListener('webkitfullscreenchange', onFullscreenChange);
  document.addEventListener('keydown', function (e) {
    // Ctrl/Cmd+C copies the terminal selection: the renderer
    // keeps no text in the DOM, so the browser's native copy
    // sees nothing to take (right-click Copy works regardless;
    // xterm fills the `copy` event itself). The viewer is
    // read-only, so the chord is free to mean "copy".
    if ((e.ctrlKey || e.metaKey) && !e.altKey &&
        (e.key === 'c' || e.key === 'C') &&
        term && term.hasSelection() && navigator.clipboard) {
      navigator.clipboard.writeText(term.getSelection())
        .catch(function () {});
      return;
    }
    if (e.defaultPrevented || e.repeat ||
        e.ctrlKey || e.metaKey || e.altKey) {
      return;
    }
    if (e.key === 'f' || e.key === 'F') {
      toggleFullscreen();
    } else if (e.key === 'Escape' && isFullscreen() &&
               !nativeFullscreenElement()) {
      // Fallback mode only; native fullscreen handles its own Esc
      exitFullscreen();
    }
  });
})();
