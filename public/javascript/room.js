  // [u32 BE: N][12-byte nonce][ciphertext+16-byte tag], AES-256-GCM -
  // keyed by the URL fragment, which browsers never send to the server.
  // A --disable-encryption broadcaster sends plaintext and no fragment;
  // the size message's `encrypted` flag tells the two apart. Must stay
  // in lockstep with src/cli/crypto.rs.
  var keyHex = window.location.hash.replace(/^#/, '');
  var encryptedWithoutKey = false;
  var term = null;
