  // A user-chosen room name belongs in the tab title, an auto-generated
  // id is noise, and we can't see the broadcaster's CLI - so guess from
  // the length, which generate_room_id (src/cli/mod.rs) fixes at 18 and
  // a human name almost never hits. Mistitling a rare 18-char custom
